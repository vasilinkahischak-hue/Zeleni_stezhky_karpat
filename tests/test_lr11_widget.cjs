'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {normalizeData, readCount, calculate} = require('../js/widget.js');
const raw = JSON.parse(fs.readFileSync(path.join(__dirname, '../data/widget-data.json'),'utf8'));
const config = normalizeData(raw);
let count=0;
const test=(name,fn)=>{fn();count++; console.log('PASS',name)};
const original={route:'pip-ivan', guests:2,days:3,transport:'own',food:false,gear:false};
test('6 existing routes from catalogue',()=>{assert.equal(config.routes.length,6);assert.equal(config.routeMap.get('pip-ivan').price,2400)});
test('Happy Path base only',()=>assert.equal(calculate(config,original).total,4800));
test('Happy Path food gear transport',()=>assert.equal(calculate(config,{...original,food:true,gear:true,transport:'ivano'}).total,6870));
test('Group discount 6 guests',()=>{const v=calculate(config,{...original,guests:6,food:true,gear:true,transport:'lviv'});assert.equal(v.discount,720);assert.equal(v.total,18690)});
test('Blank input rejected',()=>assert.match(readCount('',config.rules.guests).error,/Введіть/));
test('0 rejected',()=>assert.ok(readCount('0',config.rules.guests).error));
test('negative rejected',()=>assert.ok(readCount('-5',config.rules.guests).error));
test('anomalously large rejected',()=>assert.ok(readCount('9999999999999999',config.rules.guests).error));
test('fractional guests rejected',()=>assert.ok(readCount('2.5',config.rules.guests).error));
test('fractional days normalized up',()=>{const r=readCount('2.5',config.rules.days,true);assert.equal(r.value,3);assert.ok(r.note)});
test('comma decimal normalized',()=>assert.equal(readCount('2,5',config.rules.days,true).value,3));
test('non number e rejected',()=>assert.ok(readCount('e',config.rules.guests).error));
test('Infinity rejected',()=>assert.ok(readCount('Infinity',config.rules.guests).error));
test('invalid route rejected',()=>assert.throws(()=>calculate(config,{...original,route:'missing'}),RangeError));
test('unknown transport rejected',()=>assert.throws(()=>calculate(config,{...original,transport:'constructor'}),RangeError));
test('out of bounds guests rejected at calculation',()=>assert.throws(()=>calculate(config,{...original,guests:-5}),RangeError));
test('out of bounds days rejected at calculation',()=>assert.throws(()=>calculate(config,{...original,days:100}),RangeError));
test('damaged JSON rejected',()=>assert.throws(()=>normalizeData({routes:[],rules:{}})));
test('untrusted JSON route price rejected',()=>{const d=structuredClone(raw);d.routes[0].price=-100;assert.throws(()=>normalizeData(d))});
test('duplicate route IDs rejected',()=>{const d=structuredClone(raw);d.routes[1].id=d.routes[0].id;assert.throws(()=>normalizeData(d))});
test('malicious transport property name rejected',()=>{const d=structuredClone(raw);Object.defineProperty(d.rules.transport,'__proto__',{value:{label:'bad',price:0},enumerable:true});assert.throws(()=>normalizeData(d))});
test('non number is not displayed',()=>assert.equal(Number.isFinite(calculate(config,original).total),true));
console.log(`\n${count}/${count} unit tests passed`);
